import {
  BadRequestException,
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Post,
  Query,
} from '@nestjs/common';
import {
  ApiOperation, ApiQuery, ApiResponse, ApiTags,
} from '@nestjs/swagger';

import { ApiEndpoint } from 'src/core/decorators/apiEndpoint.decorator';
import { SessionBookingsService } from './session-bookings.service';
import { SessionBookingsGateway } from './session-bookings.gateway';
import { ConfirmSessionHoldDto } from './dto/confirm-session-hold.dto';
import { CreateSessionHoldDto } from './dto/create-session-hold.dto';
import { GenerateTestTokenDto } from './dto/generate-test-token.dto';
import { GetSessionByWrapperIdDto } from './dto/get-session-by-wrapper-id.dto';
import { GetConfirmationDetailsDto } from './dto/get-confirmation-details.dto';

@Controller('session-bookings')
export class SessionBookingsController {
  constructor(
    private readonly sessionBookingsService: SessionBookingsService,
    private readonly sessionBookingsGateway: SessionBookingsGateway,
  ) { }

  /**
   * ⚠️ TESTING ONLY - Generate encrypted token for testing
   *
   * Development utility to generate tokens without payment flow.
   * Only available in development mode (NODE_ENV=development).
   * In production, tokens are generated by OrdersService after purchase.
   */
  @ApiEndpoint({
    tags: ['Session Bookings - Testing Only'],
    operation: 'Generate test token (dev only)',
    response: {
      status: HttpStatus.CREATED,
      description: 'Test token generated',
    },
    softBlockExtraDtoFields: true,
  })
  @HttpCode(HttpStatus.CREATED)
  @Post('test/generate-token')
  async generateTestToken(@Body() dto: GenerateTestTokenDto) {
    // Only allow in development mode
    if (process.env.NODE_ENV === 'production') {
      throw new BadRequestException(
        'This endpoint is only available in development mode',
      );
    }

    return this.sessionBookingsService.generateInviteToken({
      name: dto.name,
      email: dto.email,
      phone: dto.phone,
      wrapperId: dto.wrapperId,
      code: dto.code,
      orderProductId: dto.orderProductId,
    });
  }

  /**
   * Decrypt an encrypted invite token → return customer PII + wrapper context.
   *
   * The FE calls this on page load after extracting the token from the URL.
   * PII is returned in the HTTPS response body — never decoded in the browser from the URL.
   *
   * Possible outcomes:
   *  200 { isConsumed: false, customerName, ... }   → render booking form (pre-filled)
   *  200 { isConsumed: true,  existingBooking, ... } → render read-only locked view
   *  400 → invalid / tampered token
   *  410 → expired token
   */
  @ApiEndpoint({
    tags: ['Session Bookings - Customer'],
    operation:
      'Decrypt invite token → get pre-fill data (PII never visible in URL)',
    response: {
      status: HttpStatus.OK,
      description:
        'Token decrypted. Check isConsumed to decide which view to render.',
    },
    params: [
      {
        name: 'token',
        type: 'string',
        required: true,
        description: 'AES-256-GCM encrypted token from the email URL',
      },
    ],
    softBlockExtraDtoFields: true,
  })
  @HttpCode(HttpStatus.OK)
  @Get('resolve/:token')
  async resolveInviteToken(@Param('token') token: string) {
    return this.sessionBookingsService.resolveInviteToken(token);
  }

  @ApiTags('Session Bookings - Public')
  @ApiOperation({ summary: 'Get confirmation details for a booked session' })
  @ApiQuery({ name: 'bookingId', required: true, description: 'The booking ID' })
  @ApiResponse({ status: HttpStatus.OK, description: 'Session confirmation details retrieved successfully' })
  @HttpCode(HttpStatus.OK)
  @Get('confirmation-details')
  async getConfirmationDetails(
    @Query() dto: GetConfirmationDetailsDto,
  ) {
    return this.sessionBookingsService.getConfirmationDetails(dto.bookingId);
  }

  /**
   * Get session wrapper details with availability.
   * wrapperId is returned by resolveInviteToken — the FE passes it here.
   */
  @ApiEndpoint({
    tags: ['Session Bookings - Customer'],
    operation: 'Get session details with availability',
    response: {
      status: HttpStatus.OK,
      description: 'Session details retrieved successfully',
    },
    params: [
      {
        name: 'wrapperId',
        type: 'string',
        required: true,
        description: 'SessionWrapper ID',
      },
    ],
    softBlockExtraDtoFields: true,
  })
  @HttpCode(HttpStatus.OK)
  @Get(':wrapperId')
  async getSessionByWrapperId(
    @Param('wrapperId') wrapperId: string,
    @Query() dto: GetSessionByWrapperIdDto,
  ) {
    return this.sessionBookingsService.getSessionByWrapperId(wrapperId, dto);
  }

  /**
   * Create session holds (single or multiple) atomically.
   * Uses MongoDB transaction → prevents race conditions with concurrent bookings.
   * TTL = 7 minutes + (3 minutes × extra sessions).
   */
  @ApiEndpoint({
    tags: ['Session Bookings - Customer'],
    operation: 'Create session hold(s) (atomic, single or multiple)',
    response: {
      status: HttpStatus.CREATED,
      description: 'Session hold(s) created atomically',
    },
    softBlockExtraDtoFields: true,
  })
  @HttpCode(HttpStatus.CREATED)
  @ApiEndpoint({
    tags: ['Session Bookings - Customer'],
    operation: 'Create session hold(s) (atomic, single or multiple)',
    response: {
      status: HttpStatus.CREATED,
      description: 'Session hold(s) created atomically',
    },
    softBlockExtraDtoFields: true,
  })
  @HttpCode(HttpStatus.CREATED)
  @Post('hold')
  async createSessionHolds(@Body() dto: CreateSessionHoldDto) {
    const result = this.sessionBookingsService.createBatchSessionHolds(
      dto.token,
      dto.wrapperId,
      dto.sessions,
    );

    // Emit availability update after successful hold creation (fire-and-forget)
    result
      .then(() => {
        this.sessionBookingsGateway
          .emitAvailabilityUpdate(dto.wrapperId)
          .catch(() => {
            // Silently ignore emit errors - don't block the response
          });
      })
      .catch(() => {
        // Service error, don't emit
      });

    return result;
  }

  /**
   * Confirm a session hold → convert to CONFIRMED booking.
   *
   * Takes holdId + token.
   * Decrypts token to verify consumedAt lock.
   * Creates CONFIRMED booking from the hold.
   * Sends confirmation email with check-in QR.
   */
  @ApiEndpoint({
    tags: ['Session Bookings - Customer'],
    operation: 'Confirm session hold → create booking',
    response: {
      status: HttpStatus.OK,
      description: 'Session booking confirmed successfully',
    },
    softBlockExtraDtoFields: true,
  })
  @HttpCode(HttpStatus.OK)
  @Post('confirm')
  async confirmSessionHold(@Body() dto: ConfirmSessionHoldDto) {
    const result = await this.sessionBookingsService.confirmSessionHold(dto);

    // Emit availability update after successful confirmation (fire-and-forget)
    // Emit availability update after successful confirmation (fire-and-forget)
    if (result?.data?.wrapperId) {
      this.sessionBookingsGateway
        .emitAvailabilityUpdate(result.data.wrapperId)
        .catch(() => {
          // Silently ignore emit errors - don't block the response
        });
    }

    return result;
  }

  /**
   * Check-in endpoint for room rep.
   * Decrypts check-in token from QR → returns booking details.
   * Room rep can mark customer as ATTENDED.
   */
  @ApiEndpoint({
    tags: ['Session Bookings - Room Rep'],
    operation: 'Decrypt check-in token → get booking details',
    response: {
      status: HttpStatus.OK,
      description: 'Booking details retrieved for check-in',
    },
    params: [
      {
        name: 'token',
        type: 'string',
        required: true,
        description: 'Encrypted check-in token from QR code',
      },
    ],
    softBlockExtraDtoFields: true,
  })
  @HttpCode(HttpStatus.OK)
  @Get('checkin/:token')
  async getCheckInDetails(@Param('token') token: string) {
    return this.sessionBookingsService.getCheckInDetails(token);
  }
}
